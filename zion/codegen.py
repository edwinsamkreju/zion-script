"""Python source generator for ZION's abstract syntax tree."""
import ast
import re
from zion import ast_nodes as n
from zion.errors import ZionError

def expression(source, line):
    value = source.strip()
    rules = [
        (r"\bis\s+greater\s+than\s+or\s+equal\s+to\b", ">="),
        (r"\bis\s+less\s+than\s+or\s+equal\s+to\b", "<="),
        (r"\bis\s+not\s+equal\s+to\b", "!="),
        (r"\bis\s+greater\s+than\b", ">"),
        (r"\bis\s+less\s+than\b", "<"),
        (r"\bis\s+equal\s+to\b", "=="),
        (r"\band\b", "and"), (r"\bor\b", "or"),
        (r"\btrue\b", "True"), (r"\bfalse\b", "False"),
    ]
    for pattern, replacement in rules:
        value = re.sub(pattern, replacement, value, flags=re.I)
    try:
        ast.parse(value, mode="eval")
    except SyntaxError as exc:
        raise ZionError(f"That expression doesn't look right: {source}", line) from exc
    return value

class Generator:
    def __init__(self): self.lines, self.level = [], 0
    def emit(self, text): self.lines.append("    " * self.level + text)
    def block(self, nodes):
        for node in nodes: self.statement(node)
    def statement(self, node):
        if isinstance(node, n.Store):
            self.emit(f"{node.name} = {expression(node.value, node.line)}")
        elif isinstance(node, n.Say):
            self.emit(f"print({expression(node.value, node.line)})")
        elif isinstance(node, n.PythonStatement):
            try: ast.parse(node.source, mode="exec")
            except SyntaxError as exc:
                raise ZionError(f"Invalid Python-compatible statement: {node.source}", node.line) from exc
            self.emit(node.source)
        elif isinstance(node, n.Ask):
            self.emit(f"{node.name} = input({node.prompt})")
        elif isinstance(node, n.Math):
            op = {"add": "+", "subtract": "-", "multiply": "*", "divide": "/"}[node.operation]
            self.emit(f"result = ({expression(node.left, node.line)}) {op} ({expression(node.right, node.line)})")
        elif isinstance(node, n.If):
            for i, (condition, body) in enumerate(node.branches):
                self.emit(("if " if i == 0 else "elif ") + expression(condition, node.line) + ":")
                self.level += 1
                self.block(body)
                if not body: self.emit("pass")
                self.level -= 1
            if node.otherwise is not None:
                self.emit("else:")
                self.level += 1
                self.block(node.otherwise)
                if not node.otherwise: self.emit("pass")
                self.level -= 1
        elif isinstance(node, n.Repeat):
            self.emit(f"for _zion_index in range(int({expression(node.count, node.line)})):")
            self.level += 1
            self.block(node.body)
            if not node.body: self.emit("pass")
            self.level -= 1
        elif isinstance(node, n.ForEach):
            self.emit(f"for {node.item} in {node.collection}:")
            self.level += 1
            self.block(node.body)
            if not node.body: self.emit("pass")
            self.level -= 1
        elif isinstance(node, n.CreateList): self.emit(f"{node.name} = []")
        elif isinstance(node, n.AddToList): self.emit(f"{node.name}.append({expression(node.value, node.line)})")
        elif isinstance(node, n.Function):
            self.emit(f"def {node.name}():")
            self.level += 1
            self.block(node.body)
            if not node.body: self.emit("pass")
            self.level -= 1
        elif isinstance(node, n.RunFunction): self.emit(f"{node.name}()")
        else: raise ZionError(f"Unsupported language feature: {type(node).__name__}")
    def generate(self, program):
        self.lines = ["# Generated by ZION SCRIPT v0.1.0"]
        self.block(program.statements)
        code = "\n".join(self.lines) + "\n"
        try: ast.parse(code)
        except SyntaxError as exc: raise ZionError(f"Generated Python is invalid: {exc.msg}", exc.lineno) from exc
        return code

def generate(program): return Generator().generate(program)
